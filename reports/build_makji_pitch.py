def rect(s,x,y,w,h,c,r=False):
    q=s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if r else MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    q.fill.solid(); q.fill.fore_color.rgb=RGBColor.from_string(c); q.line.fill.background()
    if r:
        q.adjustments[0]=0.12
    return q

def txt(s,x,y,w,h,text,size=22,color=INK,bold=False):
    q=s.shapes.add_textbox(Inches(x),Inches(y),Inches(w),Inches(h))
    tf=q.text_frame; tf.word_wrap=True
    tf.margin_left=0; tf.margin_right=0; tf.margin_top=0; tf.margin_bottom=0
    for i,line in enumerate(text.split('\n')):
        p=tf.paragraphs[0] if i==0 else tf.add_paragraph()
        p.text=line; p.font.name=FONT; p.font.size=Pt(size); p.font.bold=bold; p.font.color.rgb=RGBColor.from_string(color)
        p.space_after=Pt(9)
    return q

